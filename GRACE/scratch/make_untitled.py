                "        bg_y1 = max(0, y1 - th - 8)\n",
                "        cv2.rectangle(out, (x1, bg_y1), (x1 + tw + 6, y1), color, -1)\n",
                "        cv2.putText(out, text, (x1 + 3, y1 - 4), cv2.FONT_HERSHEY_SIMPLEX, 0.52, (0, 0, 0), 2, cv2.LINE_AA)\n",
                "    return out\n"
